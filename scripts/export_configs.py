#!/usr/bin/env python
"""Export the benchmark's configuration surface to YAML under ``configs/``.

The Python dataclasses are the single source of truth; these YAML files are
*generated documentation* of the experiment matrix, not a second, divergent
configuration system. Regenerate with:

    python scripts/export_configs.py

and the diff tells you exactly what a code change did to the experiment matrix.
"""

from __future__ import annotations

import dataclasses
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import yaml  # noqa: E402

from leadbench.economics import Economics  # noqa: E402
from leadbench.evaluation.prereg import KillCriteria  # noqa: E402
from leadbench.synthetic.config import ACTIONS, DGPConfig, REGIMES  # noqa: E402
from leadbench.synthetic.mmm_dgp import MMM_REGIMES, MMMConfig  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
CONFIGS = ROOT / "configs"

HEADER = (
    "# GENERATED by scripts/export_configs.py - do not edit by hand.\n"
    "# The Python dataclasses in src/leadbench are the source of truth.\n"
)


def _dump(obj, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEADER + yaml.safe_dump(obj, sort_keys=False, default_flow_style=False))
    print(f"  wrote {path.relative_to(ROOT)}")


def main() -> int:
    print("exporting configs:")

    _dump(
        {
            "action_set_primary": list(ACTIONS),
            "defaults": dataclasses.asdict(DGPConfig()),
            "regimes": {k: v for k, v in REGIMES.items()},
        },
        CONFIGS / "datasets" / "synthetic_lead.yaml",
    )

    _dump(
        {
            "defaults": dataclasses.asdict(MMMConfig()),
            "regimes": {k: v for k, v in MMM_REGIMES.items()},
        },
        CONFIGS / "datasets" / "synthetic_mmm.yaml",
    )

    _dump(
        {
            "hillstrom": {
                "kind": "real randomized experiment",
                "n": 64000,
                "treatment": "Mens / Womens e-mail vs none (1/3 each)",
                "outcomes": ["visit", "conversion", "spend"],
                "known_costs": False,
                "known_value": "spend only",
                "licence": "public release by Kevin Hillstrom / MineThatData",
                "known_leakage": "none known",
                "limitations": "2008 retail e-mail; no agent effort, no margin",
            },
            "criteo_uplift_v2_1": {
                "kind": "real randomized experiment",
                "n": 13979592,
                "treatment": "randomized ad exposure, P(treat) ~= 0.85",
                "outcomes": ["visit", "conversion"],
                "known_costs": False,
                "known_value": False,
                "licence": "CC BY-NC-SA 4.0 (NON-COMMERCIAL)",
                "known_leakage": (
                    "v2.0 had a documented incrementality leak; v2.1 is the "
                    "corrected release and the loader refuses v2.0"
                ),
                "limitations": "no deal value, no effort; 12 anonymous features",
            },
        },
        CONFIGS / "datasets" / "real.yaml",
    )

    _dump(
        {
            "economics": dataclasses.asdict(Economics()),
            "notes": {
                "sunk_cost": (
                    "acquisition CPL is sunk once a lead exists and is excluded "
                    "from the individual decisioning track; it is included only "
                    "in the acquisition/MMM track"
                ),
                "signs": "revenue +, action cost -, agent time -, media spend -, refund -",
            },
        },
        CONFIGS / "costs" / "economics.yaml",
    )

    _dump(
        {
            "allocation_modes": {
                "ev": "value-aware constrained allocation (multiple-choice knapsack)",
                "rank": "sorted call list worked top-down until capacity is spent",
            },
            "risk_policies": {
                "ev": "maximise posterior mean EV",
                "ev_lcb10": "maximise the 10th-percentile lower bound of EV",
                "ev_lcb25": "maximise the 25th-percentile lower bound of EV",
            },
            "abstention_coverages": [0.25, 0.5, 0.75, 1.0],
            "capacity_enforcement": (
                "plans use predicted handle time; the evaluator enforces the cap "
                "with TRUE handle time and truncates by the policy's own priority"
            ),
        },
        CONFIGS / "policies" / "policies.yaml",
    )

    _dump(
        {
            "primary_metric": "net_value_per_1k_leads",
            "practical_threshold_pct": 2.0,
            "decision_rule": (
                "better only if the paired 95% bootstrap interval excludes zero "
                "AND the point estimate clears the practical threshold"
            ),
            "kill_criteria": dataclasses.asdict(KillCriteria()),
            "suites": {
                "smoke": "2 regimes x 2 seeds x 7 candidates, CI-sized",
                "lead": "19 regimes x 8 seeds x 22 candidates at 25% capacity",
                "curves": "data-size 2k-100k and capacity 5%-100% sweeps",
                "ablation": "component ablations on 5 regimes",
                "bayes": "uncertainty and hierarchy candidates, 4 regimes x 2 sizes",
                "online": "bandits vs frozen vs retrained, 5 regimes",
                "real": "Hillstrom (3 arm-splits x 2 outcomes) + Criteo (2 outcomes)",
                "mmm": "6 MMM regimes; --meridian adds Google Meridian on a subset",
            },
        },
        CONFIGS / "experiments" / "matrix.yaml",
    )

    print("done")
    return 0


if __name__ == "__main__":
    sys.exit(main())
